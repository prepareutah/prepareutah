/* Prepare Utah - wind map for the refinery guide. Shared by the build (the first view is written into the page)
   and the browser (the season and time-of-day switches redraw it). Data: wind.js, generated by scripts/wind.js.
   The data holds where the wind came FROM; everything drawn here shows where it blew TOWARD,
   because that's where smoke would drift. */
(function (root) {
  var UR = root.UR = root.UR || {};
  var DIRS = ["north", "northeast", "east", "southeast", "south", "southwest", "west", "northwest"];
  var RIM = 30;   // a wedge holding 30% of hours reaches the edge of its rose; dashed rings sit at 10% and 20%
  var R = 54;     // rose radius in map units

  function esc(s) { return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/"/g, "&quot;"); }
  function pt(cx, cy, r, deg) { var a = deg * Math.PI / 180; return (cx + r * Math.sin(a)).toFixed(1) + " " + (cy - r * Math.cos(a)).toFixed(1); }
  function pct(n) { return n < 0.5 ? "under 1%" : Math.round(n) + "%"; }
  // A wedge's area, not its length, shows the share of hours, so short wedges stay readable.
  function reach(p) { return Math.sqrt(Math.min(p, RIM) / RIM) * R; }
  function label(list, v) { for (var i = 0; i < list.length; i++) if (list[i][0] === v) return list[i][1]; return v; }
  function viewName(key) { var W = UR.wind, k = key.split("."); return label(W.seasons, k[0]) + ", " + label(W.times, k[1]).toLowerCase(); }

  // Percent of hours the wind blew toward each of k equal sectors (sector 0 is centered on north, then clockwise).
  // Each ten-degree bin is shared out in quarter-degree slices so no sector gets more bins than another.
  UR.windToward = function (v, k) {
    var o = [], w = 360 / k, i;
    for (i = 0; i < k; i++) o.push(0);
    v.c.forEach(function (n, b) {
      for (var d = b * 10 + 175.125; d < b * 10 + 185; d += 0.25) o[Math.floor(((d + w / 2) % 360) / w)] += n / 40;
    });
    return o.map(function (n) { return 100 * n / v.n; });
  };

  UR.windRoses = function (key) {
    return UR.wind.stations.map(function (st) {
      var v = st.views[key], h = '<g class="rose"><circle class="rose-bg" cx="' + st.x + '" cy="' + st.y + '" r="' + R + '"/>' +
        [10, 20].map(function (p) { return '<circle class="rose-ring" cx="' + st.x + '" cy="' + st.y + '" r="' + reach(p).toFixed(1) + '"/>'; }).join("");
      if (v && v.n) UR.windToward(v, 16).forEach(function (p, i) {
        var len = reach(p), mid = i * 22.5;
        if (len < 0.8) return;
        h += '<path class="rose-wedge" d="M' + st.x + " " + st.y + "L" + pt(st.x, st.y, len, mid - 9.6) + "A" + len.toFixed(1) + " " + len.toFixed(1) + " 0 0 1 " + pt(st.x, st.y, len, mid + 9.6) + 'Z"/>';
      });
      return h + '<text class="rose-label" x="' + st.x + '" y="' + (st.labelAbove ? st.y - R - 6 : st.y + R + 13) + '" text-anchor="middle">' + esc(st.short) + "</text></g>";
    }).join("");
  };

  UR.windMapSVG = function (key) {
    var W = UR.wind, m = W.map;
    return '<svg class="windmap" viewBox="0 0 ' + m.w + " " + m.h + '" role="img" aria-label="Map of the refinery area from Salt Lake City to Centerville. At each weather station, wedges show the directions the wind blew toward. The numbers are in the list and table that follow.">' +
      '<rect class="map-land" width="' + m.w + '" height="' + m.h + '"/>' +
      m.water.map(function (d) { return '<path class="map-water" d="' + d + '"/>'; }).join("") +
      m.roads.map(function (r) { return '<path class="map-road' + (r.major ? " major" : "") + '" d="' + r.d + '"/>'; }).join("") +
      m.labels.map(function (l) { return '<text class="map-label ' + (l.cls || "") + '" x="' + l.x + '" y="' + l.y + '"' + (l.rot ? ' transform="rotate(' + l.rot + " " + l.x + " " + l.y + ')"' : "") + ' text-anchor="' + (l.anchor || "middle") + '">' + esc(l.text) + "</text>"; }).join("") +
      '<g data-roses>' + UR.windRoses(key) + "</g>" +
      m.refineries.map(function (r) { return '<g class="map-ref"><rect x="' + (r.x - 7.5) + '" y="' + (r.y - 7.5) + '" width="15" height="15" rx="3"/><text x="' + r.x + '" y="' + (r.y + 4) + '" text-anchor="middle">' + r.n + "</text></g>"; }).join("") +
      '<g class="map-north"><path d="M' + (m.w - 22) + " 40L" + (m.w - 27) + " 54L" + (m.w - 22) + " 50L" + (m.w - 17) + ' 54Z"/><text x="' + (m.w - 22) + '" y="33" text-anchor="middle">N</text></g>' +
      '<g class="map-scale"><path d="M14 ' + (m.h - 14) + "h" + m.mile2 + '"/><text x="14" y="' + (m.h - 20) + '">2 miles</text></g>' +
      "</svg>";
  };

  function windRows(key) {
    return UR.wind.stations.map(function (st) { var v = st.views[key]; return { st: st, v: v, t: v && v.n ? UR.windToward(v, 8) : null }; });
  }

  // The short list sits in an aria-live region, so a screen reader reads it out when a switch changes.
  // The table sits outside that region, in a <details> the redraw leaves alone, so it stays open.
  UR.windList = function (key) {
    return '<p class="wind-view"><strong>Showing:</strong> ' + esc(viewName(key)) + '</p><ul class="wind-list">' + windRows(key).map(function (r) {
      if (!r.t) return "<li><strong>" + esc(r.st.short) + " station:</strong> no readings for this view.</li>";
      var top = r.t.map(function (p, i) { return [p, DIRS[i]]; }).sort(function (a, b) { return b[0] - a[0]; });
      return "<li><strong>" + esc(r.st.short) + " station:</strong> the wind blew most often toward the " + top[0][1] + " (" + pct(top[0][0]) + " of hours), then toward the " + top[1][1] + " (" + pct(top[1][0]) + " of hours). Calm or shifting, with no steady direction: " + pct(100 * r.v.calm / r.v.n) + " of hours.</li>";
    }).join("") + "</ul>";
  };

  UR.windTable = function (key) {
    var rows = windRows(key);
    return '<div class="table-wrap" tabindex="0" role="region" aria-label="Wind direction numbers"><table class="wind-table"><caption>Percent of hours the wind blew toward each direction: ' + esc(viewName(key)) + '</caption><thead><tr><th scope="col">Wind blew toward the</th>' +
      rows.map(function (r) { return '<th scope="col">' + esc(r.st.short) + "</th>"; }).join("") + "</tr></thead><tbody>" +
      DIRS.map(function (d, i) { return '<tr><th scope="row">' + d.charAt(0).toUpperCase() + d.slice(1) + "</th>" + rows.map(function (r) { return "<td>" + (r.t ? pct(r.t[i]) : "no readings") + "</td>"; }).join("") + "</tr>"; }).join("") +
      '<tr><th scope="row">Calm or shifting (no steady direction)</th>' + rows.map(function (r) { return "<td>" + (r.t ? pct(100 * r.v.calm / r.v.n) : "no readings") + "</td>"; }).join("") + "</tr>" +
      '<tr><th scope="row">Hourly readings counted</th>' + rows.map(function (r) { return "<td>" + (r.v ? r.v.n.toLocaleString("en-US") : "0") + "</td>"; }).join("") + "</tr>" +
      "</tbody></table></div>";
  };

  if (!root.document) return;
  document.addEventListener("DOMContentLoaded", function () {
    var box = document.querySelector("[data-windmap]"); if (!box || !UR.wind) return;
    var season = box.querySelector("[data-wind-season]"), time = box.querySelector("[data-wind-time]");
    var shown = "all.all";   // the view the build wrote into the page
    function draw() {
      var key = season.value + "." + time.value;
      if (key === shown) return;
      shown = key;
      box.querySelector("[data-roses]").innerHTML = UR.windRoses(key);
      box.querySelector("[data-wind-list]").innerHTML = UR.windList(key);
      box.querySelector("[data-wind-table]").innerHTML = UR.windTable(key);
    }
    season.addEventListener("change", draw); time.addEventListener("change", draw);
    window.addEventListener("pageshow", draw);   // browsers can restore the selects (Back, reload, reopened tab) without firing change
    box.querySelector(".wind-controls").hidden = false;   // hidden in the HTML until this script can run them
    draw();
  });
})(typeof window !== "undefined" ? window : globalThis);
